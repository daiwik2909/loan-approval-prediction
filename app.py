"""FastAPI prediction service for the loan_status model.

Routes
  GET  /         -> static/index.html (the web UI)
  GET  /health   -> service and model status
  POST /predict  -> validated applicant data in, prediction out
  GET  /docs     -> Swagger UI (generated by FastAPI)
"""
from __future__ import annotations

import json
import logging
import os
import uuid
from contextlib import asynccontextmanager
from datetime import datetime, timezone
from pathlib import Path
from typing import Literal

import joblib
import pandas as pd
from fastapi import FastAPI, HTTPException
from fastapi.responses import FileResponse
from pydantic import BaseModel, ConfigDict, Field, model_validator

from loan_features import RAW_FEATURES  # also makes LoanFeatureEngineer importable for joblib

BASE_DIR = Path(__file__).resolve().parent
MODEL_PATH = Path(os.getenv("MODEL_PATH", BASE_DIR / "model" / "model.joblib"))
THRESHOLD = 0.5
logger = logging.getLogger("loan-api")


def prediction_log_path() -> Path:
    """Read at call time so tests can redirect logs to a temporary file."""
    return Path(os.getenv("PREDICTION_LOG_PATH", BASE_DIR / "logs" / "predictions.jsonl"))


@asynccontextmanager
async def lifespan(app: FastAPI):
    # Load the model ONCE at startup, never inside the request handler.
    app.state.model = joblib.load(MODEL_PATH)
    meta_path = MODEL_PATH.with_name("metadata.json")
    app.state.metadata = json.loads(meta_path.read_text()) if meta_path.exists() else {}
    logger.info("Model loaded from %s", MODEL_PATH)
    yield


app = FastAPI(
    title="Loan Approval Prediction API",
    description=("Educational ML service for the Kaggle 'Loan Approval Prediction ULIMA' competition. "
                 "Returns the model's probability that loan_status = 1. Not a real lending decision."),
    version="1.0.0",
    lifespan=lifespan,
)


class LoanApplication(BaseModel):
    """Input contract. Bounds match the data contract table in README.md."""
    model_config = ConfigDict(extra="forbid", json_schema_extra={"example": {
        "person_age": 28, "person_income": 60000, "person_home_ownership": "RENT",
        "person_emp_length": 4.0, "loan_intent": "EDUCATION", "loan_grade": "B",
        "loan_amnt": 9000, "loan_int_rate": 11.0, "loan_percent_income": 0.15,
        "cb_person_default_on_file": "N", "cb_person_cred_hist_length": 5}})

    person_age: int = Field(..., ge=18, le=100, description="Applicant age in years")
    person_income: float = Field(..., ge=1000, le=2_000_000, description="Annual income")
    person_home_ownership: Literal["RENT", "OWN", "MORTGAGE", "OTHER"]
    person_emp_length: float = Field(..., ge=0, le=60, description="Years employed")
    loan_intent: Literal["EDUCATION", "MEDICAL", "PERSONAL", "VENTURE",
                         "DEBTCONSOLIDATION", "HOMEIMPROVEMENT"]
    loan_grade: Literal["A", "B", "C", "D", "E", "F", "G"]
    loan_amnt: float = Field(..., ge=500, le=35_000, description="Requested loan amount")
    loan_int_rate: float = Field(..., ge=5.0, le=25.0, description="Interest rate in percent")
    loan_percent_income: float = Field(..., ge=0, le=1, description="Loan amount / annual income")
    cb_person_default_on_file: Literal["N", "Y"]
    cb_person_cred_hist_length: int = Field(..., ge=0, le=60, description="Credit history in years")

    @model_validator(mode="after")
    def check_consistency(self):
        if self.person_emp_length > self.person_age - 14:
            raise ValueError("person_emp_length cannot exceed person_age - 14")
        if self.cb_person_cred_hist_length > self.person_age - 14:
            raise ValueError("cb_person_cred_hist_length cannot exceed person_age - 14")
        return self


class PredictionResponse(BaseModel):
    loan_status: Literal[0, 1]
    probability: float = Field(..., description="Model probability that loan_status = 1")
    label: str
    threshold: float
    disclaimer: str


@app.get("/", include_in_schema=False)
def home():
    return FileResponse(BASE_DIR / "static" / "index.html")


@app.get("/health")
def health():
    meta = getattr(app.state, "metadata", {})
    return {
        "status": "ok",
        "model_loaded": getattr(app.state, "model", None) is not None,
        "model": meta.get("params", {}).get("model"),
        "cv_roc_auc": meta.get("metrics", {}).get("cv_roc_auc_mean"),
    }


def log_prediction(features: dict, probability: float, status: int) -> None:
    """Append one JSON line per prediction for drift monitoring.

    Only the model's input features are logged (no names, IDs or IP addresses).
    A logging failure never breaks the prediction itself.
    """
    record = {"request_id": str(uuid.uuid4()),
              "timestamp": datetime.now(timezone.utc).isoformat(timespec="seconds"),
              **features, "probability": round(probability, 6), "loan_status": status}
    try:
        path = prediction_log_path()
        path.parent.mkdir(parents=True, exist_ok=True)
        with path.open("a", encoding="utf-8") as f:
            f.write(json.dumps(record) + "\n")
    except OSError as exc:
        logger.warning("Could not write prediction log: %s", exc)


@app.post("/predict", response_model=PredictionResponse)
def predict(application: LoanApplication):
    model = getattr(app.state, "model", None)
    if model is None:
        raise HTTPException(status_code=503, detail="Model not loaded")
    features = application.model_dump()
    X = pd.DataFrame([features], columns=RAW_FEATURES)
    probability = float(model.predict_proba(X)[0, 1])
    status = int(probability >= THRESHOLD)
    log_prediction(features, probability, status)
    return PredictionResponse(
        loan_status=status,
        probability=round(probability, 4),
        label="High-risk profile (loan_status = 1)" if status else "Lower-risk profile (loan_status = 0)",
        threshold=THRESHOLD,
        disclaimer="Educational ML prediction only. Not a real credit or lending decision.",
    )
